-- DEAD QUEUE HISTORY
CREATE TABLE IF NOT EXISTS MESSAGE_DEAD_HISTORY (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    created_date TIMESTAMP NOT NULL,
    exchange_name VARCHAR(255) NOT NULL,
    queue_name VARCHAR(255) NOT NULL,
    routing_header VARCHAR(1000),
    message_id VARCHAR(255),
    payload TEXT NOT NULL
);

-- JOBS
CREATE TABLE IF NOT EXISTS dead_queue_job_config (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    queue_name VARCHAR(255) NOT NULL UNIQUE,
    delay_minutes INT NOT NULL,
    batch_size INT NOT NULL,
    initial_delay_seconds INT NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    description VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
    );

CREATE INDEX IF NOT EXISTS idx_enabled ON dead_queue_job_config(enabled);
